"""build: make every skill self-contained and package the downloads.

    python3 build.py          # sync shared/ into each skill, write the router playbooks, zip into dist/
    python3 build.py --check  # exit 1 if any skill is out of sync with shared/ (use before committing)

Edit ONLY shared/ (scripts, reference, templates) and skills/<name>/SKILL.md. Everything else is generated:
    skills/<name>/scripts, reference, templates      copies of shared/
    skills/vibe-editing-system/reference/types/*.md  the 8 playbooks, so the start-here skill works alone
    dist/<name>.zip                                  one download per skill (upload to Claude or unzip into ~/.claude/skills)
    dist/vibe-editing-system-all.zip                 every skill in one download
"""

import filecmp
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SHARED = ROOT / "shared"
SKILLS = ROOT / "skills"
DIST = ROOT / "dist"
ROUTER = "vibe-editing-system"
PARTS = ("scripts", "reference", "templates")
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store", "node_modules")


def skill_dirs():
    return sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").exists())


def frontmatter(path):
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        sys.exit(f"{path}: missing YAML frontmatter")
    meta = dict(re.findall(r"^(\w[\w-]*):\s*(.*)$", m.group(1), re.M))
    return meta, m.group(2)


def validate(d):
    meta, _ = frontmatter(d / "SKILL.md")
    errs = []
    if meta.get("name") != d.name:
        errs.append(f"name '{meta.get('name')}' must equal folder '{d.name}'")
    if not re.fullmatch(r"[a-z0-9-]{1,64}", meta.get("name", "")):
        errs.append("name must be lowercase letters, digits, hyphens (<= 64)")
    desc = meta.get("description", "")
    if not desc or len(desc) > 1024:
        errs.append(f"description must be 1..1024 chars (is {len(desc)})")
    if "<" in desc or ">" in desc:
        errs.append("description must not contain < or >")
    lines = (d / "SKILL.md").read_text().count("\n")
    if lines > 500:
        errs.append(f"SKILL.md is {lines} lines; keep it under 500 and move detail to reference/")
    return errs


def playbooks():
    """type playbooks for the router: each type skill's body, paths still valid inside the router folder."""
    out = {}
    for d in skill_dirs():
        if d.name == ROUTER:
            continue
        meta, body = frontmatter(d / "SKILL.md")
        out[d.name] = (f"<!-- generated by build.py from skills/{d.name}/SKILL.md; do not edit here -->\n"
                       f"> Playbook **{d.name}**: {meta['description']}\n\n{body.lstrip()}")
    return out


def sync():
    books = playbooks()
    for d in skill_dirs():
        for part in PARTS:
            dst = d / part
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(SHARED / part, dst, ignore=IGNORE)
        if d.name == ROUTER:
            tdir = d / "reference" / "types"
            tdir.mkdir(parents=True, exist_ok=True)
            for name, text in books.items():
                (tdir / f"{name}.md").write_text(text)


def dircmp_equal(a, b):
    c = filecmp.dircmp(a, b, ignore=["__pycache__", ".DS_Store", "types"])
    if c.left_only or c.right_only or c.diff_files or c.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, c.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(dircmp_equal(Path(a) / s, Path(b) / s) for s in c.common_dirs)


def check():
    bad = []
    books = playbooks()
    for d in skill_dirs():
        bad += [f"{d.name}: {e}" for e in validate(d)]
        for part in PARTS:
            if not (d / part).exists() or not dircmp_equal(SHARED / part, d / part):
                bad.append(f"{d.name}/{part} differs from shared/{part}")
        if d.name == ROUTER:
            for name, text in books.items():
                p = d / "reference" / "types" / f"{name}.md"
                if not p.exists() or p.read_text() != text:
                    bad.append(f"{ROUTER}/reference/types/{name}.md is stale")
    return bad


def zip_dir(zf, folder, arc_root):
    for p in sorted(folder.rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts and p.name != ".DS_Store":
            info = zipfile.ZipInfo(str(Path(arc_root) / p.relative_to(folder)), date_time=(2026, 1, 1, 0, 0, 0))
            info.external_attr = (0o755 if p.suffix in (".py", ".mjs", ".sh") else 0o644) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, p.read_bytes())


def package():
    DIST.mkdir(exist_ok=True)
    for old in DIST.glob("*.zip"):
        old.unlink()
    for d in skill_dirs():
        with zipfile.ZipFile(DIST / f"{d.name}.zip", "w") as zf:
            zip_dir(zf, d, d.name)
    with zipfile.ZipFile(DIST / "vibe-editing-system-all.zip", "w") as zf:
        for d in skill_dirs():
            zip_dir(zf, d, Path("skills") / d.name)
        zf.write(ROOT / "README.md", "README.md")


def main():
    if "--check" in sys.argv:
        bad = check()
        for b in bad:
            print("  x", b)
        print("in sync" if not bad else f"{len(bad)} problem(s); run: python3 build.py")
        sys.exit(1 if bad else 0)
    for d in skill_dirs():
        errs = validate(d)
        if errs:
            sys.exit(f"{d.name}: " + "; ".join(errs))
    sync()
    package()
    for d in skill_dirs():
        z = DIST / f"{d.name}.zip"
        print(f"  {d.name:26s} {sum(1 for _ in d.rglob('*') if _.is_file()):3d} files  dist/{z.name} ({z.stat().st_size / 1024:.0f} KB)")
    print(f"  all skills -> dist/vibe-editing-system-all.zip ({(DIST / 'vibe-editing-system-all.zip').stat().st_size / 1024:.0f} KB)")
    left = check()
    if left:
        sys.exit("after build still out of sync: " + "; ".join(left))


if __name__ == "__main__":
    main()
