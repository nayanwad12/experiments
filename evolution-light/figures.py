"""Single-line outlines for each chapter of the story.

Every figure is a list of strokes. A stroke is a list of 2D control points
(x forward, y up, metres, feet on y=0) plus an emission level; the light
travels between strokes with its emission switched off, like a light painter
covering the torch. Control points are smoothed with a Catmull-Rom spline.
"""
import numpy as np


def catmull_rom(pts, samples_per_seg=24, closed=False):
    p = np.asarray(pts, dtype=float)
    if closed:
        p = np.vstack([p[-1], p, p[0], p[1]])
    else:
        p = np.vstack([2 * p[0] - p[1], p, 2 * p[-1] - p[-2]])
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        # centripetal parameterisation avoids cusps and self-loops
        def tj(ti, a, b):
            return ti + max(np.linalg.norm(b - a), 1e-6) ** 0.5
        t0 = 0.0
        t1 = tj(t0, p0, p1)
        t2 = tj(t1, p1, p2)
        t3 = tj(t2, p2, p3)
        t = np.linspace(t1, t2, samples_per_seg, endpoint=False)[:, None]
        a1 = (t1 - t) / (t1 - t0) * p0 + (t - t0) / (t1 - t0) * p1
        a2 = (t2 - t) / (t2 - t1) * p1 + (t - t1) / (t2 - t1) * p2
        a3 = (t3 - t) / (t3 - t2) * p2 + (t - t2) / (t3 - t2) * p3
        b1 = (t2 - t) / (t2 - t0) * a1 + (t - t0) / (t2 - t0) * a2
        b2 = (t3 - t) / (t3 - t1) * a2 + (t - t1) / (t3 - t1) * a3
        out.append((t2 - t) / (t2 - t1) * b1 + (t - t1) / (t2 - t1) * b2)
    out.append(p[-2][None])
    return np.vstack(out)


def circle(cx, cy, r, start=0.0, turns=1.0, n=14):
    a = start + np.linspace(0, 2 * np.pi * turns, n)
    return [(cx + r * np.cos(t), cy + r * np.sin(t)) for t in a]


